const RESOURCE_KEYS: (keyof OfficialResource)[] = [
  'id',
  'jurisdiction',
  'title',
  'url',
  'kind',
  'format',
  'verifiedOn',
  'verificationStatus',
  'sourceLocation',
  'notes',
];

const JURISDICTIONS: OfficialResource['jurisdiction'][] = [
  'hrm',
  'cbrm',
  'truro',
  'kentville',
  'bridgewater',
  'other_ns',
  'nova_scotia',
];

const KINDS: OfficialResource['kind'][] = [
  'application_form',
  'requirements',
  'guidance',
  'portal',
  'renewal_guidance',
];

/** Runtime guard preserving the EXACT OfficialResource schema (ten fields, fixed domains). */
export function isOfficialResource(value: unknown): value is OfficialResource {
  if (typeof value !== 'object' || value === null) return false;
  const v = value as Record<string, unknown>;
  if (Object.keys(v).length !== RESOURCE_KEYS.length) return false;
  for (const k of RESOURCE_KEYS) {
    if (typeof v[k] !== 'string' || (v[k] as string).length === 0) return false;
  }
  if (!(JURISDICTIONS as string[]).includes(v['jurisdiction'] as string)) return false;
  if (!(KINDS as string[]).includes(v['kind'] as string)) return false;
  if (v['format'] !== 'pdf' && v['format'] !== 'web') return false;
  if (v['verificationStatus'] !== 'verified' && v['verificationStatus'] !== 'needs_review') return false;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(v['verifiedOn'] as string)) return false;
  if (typeof v['url'] !== 'string' || !/^https:\/\//.test(v['url'] as string)) return false;
  return true;
}

/** Validate an external catalog (e.g. a future JSON import) against the exact schema. Throws on any deviation. */
export function validateCatalog(list: unknown): OfficialResource[] {
  if (!Array.isArray(list)) throw new Error('Official resource catalog must be an array.');
  const ids = new Set<string>();
  for (const entry of list) {
    if (!isOfficialResource(entry)) {
      throw new Error(`Invalid OfficialResource entry: ${JSON.stringify(entry)?.slice(0, 160) ?? 'unknown'}.`);
    }
    if (ids.has(entry.id)) throw new Error(`Duplicate OfficialResource id "${entry.id}".`);
    ids.add(entry.id);
  }
  return [...list];
}

export function loadResourceCatalog(): OfficialResource[] {
  return validateCatalog(OFFICIAL_RESOURCES);
}

/**
 * Municipality-scoped catalog: entries for the given municipality PLUS
 * province-wide (`nova_scotia`) entries. No HRM rules outside HRM — each
 * municipality sees only its own entries and shared provincial guidance.
 */
export function resourcesFor(
  municipality: JurisdictionId | 'nova_scotia',
  catalog: OfficialResource[] = OFFICIAL_RESOURCES,
): OfficialResource[] {
  return catalog.filter((r) => r.jurisdiction === municipality || r.jurisdiction === 'nova_scotia');
}

export function applicationForms(list: OfficialResource[]): OfficialResource[] {
  return list.filter((r) => r.kind === 'application_form');
}

/** Requirements tables, checklists, handouts, bylaws, bulletins, hubs — never application forms. */
export function requirementsAndGuidance(list: OfficialResource[]): OfficialResource[] {
  return list.filter((r) => r.kind === 'requirements' || r.kind === 'guidance' || r.kind === 'renewal_guidance');
}

export function portalEntries(list: OfficialResource[]): OfficialResource[] {
  return list.filter((r) => r.kind === 'portal');
}

export function kindLabel(kind: OfficialResource['kind']): string {
  if (kind === 'application_form') return 'Application form';
  if (kind === 'requirements') return 'Requirements';
  if (kind === 'guidance') return 'Guidance';
  if (kind === 'portal') return 'Portal (manual)';
  return 'Renewal guidance';
}

