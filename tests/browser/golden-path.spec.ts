import { test, expect, type Page } from '@playwright/test';
import { resolve } from 'node:path';
const fixture = (name: string) => resolve('deliverables/qa', name);
const stat = (page: Page, name: string) => page.locator('.stat-row').getByText(name, { exact: true }).locator('..').locator('dd');

test('synthetic project: inspect, upload, correct, re-evaluate and export', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', err => errors.push(err.message));
  await page.goto('/workspace');
  await expect(page.getByText('Juniper Studio storefront renovation', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open workspace' }).first().click();
  await expect(stat(page, 'Possible gaps')).toHaveText('1');
  await expect(stat(page, 'Conflicts')).toHaveText('1');
  await expect(stat(page, 'Unknown')).toHaveText('2');
  await page.getByRole('tab', { name: 'Requirements', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search requirements' }).fill('Building Elevations');
  const elevation = page.locator('.req-list > li').filter({ hasText: 'Building Elevations' });
  await expect(elevation.getByRole('link', { name: 'Official source' })).toHaveAttribute('href', 'https://www.halifax.ca/media/72812');
  await expect(elevation).toContainText('dangling');
  await elevation.getByRole('button', { name: 'Acknowledge missing evidence' }).click();
  await elevation.getByRole('textbox').fill('Synthetic demo: collecting the elevation summary; source ambiguity still needs qualified review.');
  await elevation.getByRole('button', { name: /Save|Record/ }).click();
  await expect(elevation).toContainText('Missing evidence');
  await expect(elevation).toContainText('Acknowledged');
  await page.getByRole('tab', { name: /Documents/ }).click();
  await page.locator('input[type=file]').setInputFiles(fixture('A-201-Elevations.pdf'));
  const uploaded = page.locator('.doc-list > li').filter({ hasText: 'A-201-Elevations.pdf' });
  await expect(uploaded).toBeVisible({ timeout: 30_000 });
  await uploaded.getByRole('button', { name: 'Evidence detail' }).click();
  await expect(page.getByRole('dialog')).toContainText('120 Example Lane');
  await page.getByRole('dialog').getByRole('button', { name: /Close/ }).click();
  const conflicting = page.locator('.doc-list > li').filter({ hasText: 'SYNTHETIC project-description-wrong-address.txt' });
  await conflicting.getByRole('button', { name: 'Remove', exact: true }).click();
  await conflicting.getByRole('button', { name: 'Yes, remove', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles(fixture('replacement-project-description.txt'));
  await expect(page.locator('.doc-list > li').filter({ hasText: 'replacement-project-description.txt' })).toBeVisible({ timeout: 30_000 });
  await page.getByRole('tab', { name: 'Overview', exact: true }).click();
  await page.getByRole('button', { name: 'Re-evaluate', exact: true }).click();
  await expect(stat(page, 'Possible gaps')).toHaveText('0');
  await expect(stat(page, 'Conflicts')).toHaveText('0');
  await expect(stat(page, 'Unknown')).toHaveText('2');
  await page.getByRole('button', { name: 'Preview report', exact: true }).click();
  await expect(page.locator('.report-preview a[href="https://www.halifax.ca/media/72812"]').first()).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export report', exact: true }).first().click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/^PermitPath-.*\.pdf$/);
  await download.saveAs(info.outputPath('readiness-report.pdf'));
  await page.screenshot({ path: info.outputPath('resolved-workspace.png'), fullPage: true });
  await page.reload();
  await page.getByRole('button', { name: 'Open workspace' }).first().click();
  await expect(stat(page, 'Conflicts')).toHaveText('0');
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('create a project with square-metre facts and preserve it after reload', async ({ page }) => {
  await page.goto('/workspace');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByLabel('Project name').fill('Synthetic new workspace');
  await page.getByLabel(/Site address/).fill('140 Example Lane, Halifax, NS (synthetic)');
  await page.getByLabel(/Proposed Total Area/).pressSequentially('450.5');
  await page.getByLabel(/^Storeys/).fill('2');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Synthetic new workspace' })).toBeVisible();
  await page.getByRole('tab', { name: 'Project details', exact: true }).click();
  await expect(page.getByLabel(/Proposed Total Area/)).toHaveValue('450.5');
  await page.reload();
  await expect(page.getByText('Synthetic new workspace', { exact: true })).toBeVisible();
});
